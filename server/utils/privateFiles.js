const fs = require("fs");
const path = require("path");

// Protected storage: never mounted as a static directory, only read through authorised endpoints
const STORAGE_ROOT = process.env.PRIVATE_STORAGE_DIR
  ? path.resolve(process.env.PRIVATE_STORAGE_DIR)
  : path.resolve(__dirname, "..", "storage");

const SIGNATURES = [
  { mime: "image/png", ext: "png", test: (b) => b.length > 8 && b.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])) },
  { mime: "image/jpeg", ext: "jpg", test: (b) => b.length > 3 && b[0] === 0xff && b[1] === 0xd8 && b[2] === 0xff },
];

// Resolves a stored relative path and refuses anything that escapes the storage root
const resolveSafe = (relPath) => {
  if (!relPath || typeof relPath !== "string") return null;
  const full = path.resolve(STORAGE_ROOT, relPath);
  if (full !== STORAGE_ROOT && !full.startsWith(STORAGE_ROOT + path.sep)) return null;
  return full;
};

// Validates a PNG/JPEG data URL by its real file signature (not the claimed type) and size
const parseImageDataUrl = (dataUrl, maxBytes) => {
  const match = /^data:image\/(png|jpe?g);base64,([A-Za-z0-9+/=\r\n]+)$/.exec(dataUrl || "");
  if (!match) return { error: "Upload a JPG or PNG image" };
  const buffer = Buffer.from(match[2], "base64");
  if (buffer.length === 0) return { error: "The image is empty" };
  if (buffer.length > maxBytes) return { error: `The image is too large (maximum ${Math.round(maxBytes / 1024 / 1024)} MB)` };
  const sig = SIGNATURES.find((s) => s.test(buffer));
  if (!sig) return { error: "The file is not a valid JPG or PNG image" };
  return { buffer, mime: sig.mime, ext: sig.ext };
};

// `dir` and `baseName` are generated by the server (never taken from user input)
const saveImage = async (dir, baseName, parsed) => {
  const rel = path.join(dir, `${baseName}.${parsed.ext}`);
  const full = resolveSafe(rel);
  if (!full) throw new Error("Unsafe storage path");
  await fs.promises.mkdir(path.dirname(full), { recursive: true });
  await fs.promises.writeFile(full, parsed.buffer, { mode: 0o600 });
  return rel.split(path.sep).join("/");
};

const readAsDataUrl = async (relPath, mime) => {
  const full = resolveSafe(relPath);
  if (!full) return null;
  try {
    const buf = await fs.promises.readFile(full);
    return `data:${mime || "image/png"};base64,${buf.toString("base64")}`;
  } catch (err) {
    if (err.code === "ENOENT") return null;
    throw err;
  }
};

const removeFile = async (relPath) => {
  const full = resolveSafe(relPath);
  if (!full) return;
  await fs.promises.unlink(full).catch(() => {});
};

module.exports = { STORAGE_ROOT, parseImageDataUrl, saveImage, readAsDataUrl, removeFile, resolveSafe };
